// @ts-check

// Distills glossary.md, the-world.md and general-rules.md, in that order, to stdout: the
// glossary, the world's Scope and Forces, the general rules' Assumptions, verbatim; of each
// property its statement, Except and Against; of each rule its Scope, Statement and Examples.
// No group files: the world and the general rules group the situations already.
// Usage: node docs/layers-revamp/distill.mjs > distilled.md

import { existsSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const PREAMBLE = `# Layers, distilled

Generated by \`distill.mjs\` from \`glossary.md\`, \`the-world.md\` and \`general-rules.md\`; not
edited by hand. No Why, Relies on or Provenance: what binds is here.

- The glossary below applies to this file only. A repository may define some terms otherwise;
  reading the rules and properties below with its meanings warps them.
- Forces: what the world does to a system. Properties: what holds anyway. *Against* names the
  forces a property holds against; *Except*, what it does not cover.
- A rule is its Scope and Statement read as one. Where the Scope does not hold, the rule says
  nothing. Where two Scopes hold, the narrower governs.
- MUST, MUST NOT: no deviation. SHOULD, SHOULD NOT: the default; deviating takes an ADR naming
  the rule id. MAY: a permission where another rule would forbid.
- Examples name files by their absolute path in the repository; \`—\` means unfinished.`

/** @param {string} name */
const read = name => readFileSync(new URL(name, import.meta.url), "utf8")

/** @param {string} text */
const demote = text => text.replace(/^(#+) /gm, "#$1 ")

const EXAMPLES = fileURLToPath(new URL("examples/", import.meta.url))

/**
 * Names a rule's examples by their absolute path, so the output resolves them wherever it lands.
 * Throws on a file that does not exist.
 * @param {string} text
 */
const resolveExamples = text =>
    text
        .split(/(\s)/)
        .map(word => {
            if (!word.startsWith("examples/")) {
                return word
            }
            const path = EXAMPLES + word.slice("examples/".length)
            if (!existsSync(path)) {
                throw new Error(`missing example: ${word}`)
            }
            return path
        })
        .join("")

/**
 * The `## ` sections of a document; the title and intro before the first are dropped.
 * @param {string} text
 */
const sections = text =>
    text
        .split(/^## /m)
        .slice(1)
        .map(chunk => {
            const [title = "", ...body] = chunk.split("\n")
            return { title, body: body.join("\n").trim() }
        })

/**
 * Splits a section into entries at each line `pattern` matches; its first group is the entry's
 * heading. Throws on text before the first entry.
 * @param {string} body
 * @param {RegExp} pattern
 */
const entries = (body, pattern) => {
    const [before = "", ...rest] = body.split(pattern)
    if (before.trim()) {
        throw new Error(`text before first entry: ${before.trim().slice(0, 80)}`)
    }
    /** @type {{ heading: string, lines: string[] }[]} */
    const out = []
    for (let i = 0; i < rest.length; i += 2) {
        out.push({ heading: rest[i] ?? "", lines: (rest[i + 1] ?? "").trim().split("\n") })
    }
    return out
}

const LABEL = /^\*([A-Z][a-z]+(?: [a-z]+)*):\*/

/**
 * The labeled parts of an entry, wanted ones only, in the order given. A part runs from its
 * `*Label:*` line to the next. Throws on an unknown label or a missing required one.
 * @param {{ heading: string, lines: string[] }} entry
 * @param {{ known: string[], wanted: string[], required: string[] }} labels
 */
const parts = ({ heading, lines }, { known, wanted, required }) => {
    /** @type {Map<string, string[]>} */
    const found = new Map()
    /** @type {string[] | undefined} */
    let current
    for (const line of lines) {
        const label = line.match(LABEL)?.[1]
        if (label !== undefined) {
            if (!known.includes(label)) {
                throw new Error(`${heading}: unknown label ${label}`)
            }
            current = [line]
            found.set(label, current)
        } else if (current) {
            current.push(line)
        } else if (line.trim()) {
            throw new Error(`${heading}: text before first label: ${line}`)
        }
    }
    for (const label of required) {
        if (!found.has(label)) {
            throw new Error(`${heading}: missing ${label}`)
        }
    }
    return wanted.flatMap(label => found.get(label)?.join("\n").trim() ?? [])
}

const PROPERTY = {
    known: ["Except", "Against", "Why", "Provenance"],
    wanted: ["Except", "Against"],
    required: ["Against"],
}

const RULE = {
    known: ["Scope", "Statement", "Relies on", "Why", "Provenance", "Examples"],
    wanted: ["Scope", "Statement", "Examples"],
    required: ["Scope", "Statement", "Examples"],
}

const out = [PREAMBLE, "## Glossary"]
out.push(...sections(read("glossary.md")).map(({ title, body }) => `### ${title}\n\n${demote(body)}`))

out.push("## The world")
for (const { title, body } of sections(read("the-world.md"))) {
    if (title === "Scope" || title === "Forces") {
        out.push(`### ${title}`, demote(body))
    } else if (title === "Properties") {
        out.push("### Properties")
        for (const entry of entries(body, /^### (P\d+\. .*)$/m)) {
            const [id, ...statement] = entry.heading.split(" ")
            out.push([`**${id}** ${statement.join(" ")}`, ...parts(entry, PROPERTY)].join("\n"))
        }
    } else {
        throw new Error(`the-world.md: unknown section ${title}`)
    }
}

out.push("## General rules")
for (const { title, body } of sections(read("general-rules.md"))) {
    if (title === "Assumptions") {
        out.push(`### ${title}`, demote(body))
    } else if (title !== "Sources" && title !== "Retired ids") {
        out.push(`### ${title}`)
        for (const entry of entries(body, /^(\*\*[A-Z]+-\d+\*\*)$/m)) {
            out.push([entry.heading, ...parts(entry, RULE).map(resolveExamples)].join("\n"))
        }
    }
}

process.stdout.write(`${out.join("\n\n")}\n`)
